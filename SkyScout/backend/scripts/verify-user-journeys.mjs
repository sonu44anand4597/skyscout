import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import mongoose from 'mongoose';
import connectDB from '../config/database.js';
import { browserSession, until, pause } from './browser-session.mjs';
import User from '../models/User.js';
import AuthSession from '../models/AuthSession.js';
import TrackedFlight from '../models/TrackedFlight.js';
import PriceObservation from '../models/PriceObservation.js';
import Notification from '../models/Notification.js';
import DisruptionPrediction from '../models/DisruptionPrediction.js';
import FareIntelligenceAnalysis from '../models/FareIntelligenceAnalysis.js';
import IntelligenceReport from '../models/IntelligenceReport.js';

const email = `browser-${randomUUID()}@example.test`;
const password = randomUUID();
const web = process.env.E2E_WEB_URL || 'http://127.0.0.1:5173';
const evidence = { executedAt: new Date().toISOString(), source: 'Actual browser forms → Express → MongoDB; LIVE airport autocomplete and flight search', checks: {} };
let browser; let userId;
try {
  await connectDB();
  browser = await browserSession();
  const { call, evaluate, fill } = browser;
  await call('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await call('Page.navigate', { url: `${web}/register` });
  await until(() => evaluate(`Boolean(document.querySelector('input[autocomplete="name"]'))`), 'registration form');
  await fill('input[autocomplete="name"]', 'Browser journey verification'); await fill('input[type="email"]', email); await fill('input[type="password"]', password);
  await evaluate(`document.querySelector('form button').click()`);
  await until(() => evaluate(`location.pathname === '/dashboard' && document.body.innerText.includes('Your dashboard')`), 'browser registration');
  userId = (await User.findOne({ email }).lean())._id; evidence.checks.browserRegistration = true;
  await call('Page.navigate', { url: web });
  await until(() => evaluate(`document.querySelectorAll('#flight-search input[role="combobox"]').length === 2`), 'search form');
  await evaluate(`document.querySelectorAll('#flight-search input[role="combobox"]')[0].focus()`);
  await call('Input.insertText', { text: 'Delhi' });
  await until(() => evaluate(`Array.from(document.querySelectorAll('[role="option"]')).some((item) => item.innerText.includes('DEL'))`), 'live origin autocomplete');
  await evaluate(`Array.from(document.querySelectorAll('[role="option"]')).find((item) => item.innerText.includes('DEL')).click()`);
  await evaluate(`document.querySelectorAll('#flight-search input[role="combobox"]')[1].focus()`);
  await call('Input.insertText', { text: 'Bengaluru' });
  await until(() => evaluate(`Array.from(document.querySelectorAll('[role="option"]')).some((item) => item.innerText.includes('BLR'))`), 'live destination autocomplete');
  await evaluate(`Array.from(document.querySelectorAll('[role="option"]')).find((item) => item.innerText.includes('BLR')).click()`);
  const departure = new Date(Date.now() + 28 * 86400000).toISOString().slice(0, 10);
  await fill('#flight-search input[type="date"]', departure);
  await evaluate(`Array.from(document.querySelectorAll('#flight-search button')).find((button) => button.textContent.includes('Search flights')).click()`);
  await until(() => evaluate(`location.pathname === '/results' && Boolean(document.querySelector('article button'))`), 'live browser flight results');
  evidence.checks.autocompleteAndSearch = true;
  const ceiling = await evaluate(`Number(document.querySelector('input[aria-label="Maximum fare"]').max)`);
  assert.ok(ceiling > 10000); evidence.checks.priceFilterIncludesRealFaresAbove10000 = true;
  await evaluate(`Array.from(document.querySelector('article').querySelectorAll('button')).find((button) => button.textContent === 'Track this flight').click()`);
  await until(() => evaluate(`document.querySelector('article').innerText.includes('Tracking')`), 'browser tracking action');
  const flight = await TrackedFlight.findOne({ userId }).lean(); assert.ok(flight);
  assert.equal(await PriceObservation.countDocuments({ trackedFlightId: flight._id }), 1);
  evidence.checks.trackingPersisted = true;
  await call('Page.navigate', { url: `${web}/dashboard?flight=${flight._id}` });
  await until(() => evaluate(`Boolean(document.querySelector('section[aria-label="Fare Intelligence"] button[aria-pressed]'))`), 'fare intelligence controls');
  await until(() => evaluate(`Array.from(document.querySelectorAll('#tracked-flight-${flight._id} button')).some((button) => button.textContent === 'Pause')`), 'loaded watchlist pause control');
  await evaluate(`document.querySelector('#tracked-flight-${flight._id} button').click()`);
  await until(async () => (await TrackedFlight.findById(flight._id).lean()).status === 'paused', 'pause persisted');
  await until(() => evaluate(`Array.from(document.querySelectorAll('#tracked-flight-${flight._id} button')).some((button) => button.textContent === 'Resume')`), 'resume control');
  const target = Math.floor(flight.currentPrice / 2);
  await fill(`#tracked-flight-${flight._id} input[type="number"]`, String(target));
  await evaluate(`document.querySelector('#tracked-flight-${flight._id} input').dispatchEvent(new FocusEvent('focusout', { bubbles: true }))`);
  await until(async () => (await TrackedFlight.findById(flight._id).lean()).targetPrice === target, 'target persisted');
  evidence.checks.pauseAndTarget = true;
  await evaluate(`document.querySelector('button[aria-label="Switch to dark mode"]')?.click()`);
  await until(() => evaluate(`document.documentElement.classList.contains('dark')`), 'dark mode');
  await call('Page.reload');
  await until(() => evaluate(`document.body.innerText.includes('Your dashboard') && document.documentElement.classList.contains('dark') && location.search.includes('${flight._id}')`), 'refresh persistence');
  await until(() => evaluate(`Boolean(document.querySelector('#tracked-flight-${flight._id} input'))`), 'refreshed watchlist');
  evidence.checks.refreshAndDarkMode = true;
  await until(() => evaluate(`Array.from(document.querySelectorAll('section[aria-label="Airport weather"] summary')).some((summary) => summary.textContent === 'View TAF forecast')`), 'live TAF forecast');
  const taf = await evaluate(`(() => { const summary = Array.from(document.querySelectorAll('section[aria-label="Airport weather"] summary')).find((item) => item.textContent === 'View TAF forecast'); summary.click(); return summary.parentElement.innerText; })()`);
  evidence.tafDisplay = taf;
  assert.ok(taf.includes('Issued') && taf.includes('valid')); assert.equal(taf.includes('Time unavailable'), false, taf);
  evidence.checks.liveTafValidityRendered = true;
  await call('Emulation.setDeviceMetricsOverride', { width: 360, height: 800, deviceScaleFactor: 1, mobile: false }); await pause(300);
  assert.equal(await evaluate('document.documentElement.scrollWidth > innerWidth'), false); evidence.checks.mobile360NoOverflow = true;
  const image = await call('Page.captureScreenshot', { format: 'png' });
  await mkdir('../docs/qa/production-2026-10-28', { recursive: true });
  await writeFile('../docs/qa/production-2026-10-28/browser-journey-mobile.png', Buffer.from(image.data, 'base64'));
  await evaluate(`Array.from(document.querySelectorAll('button')).find((button) => button.textContent.includes('Sign out')).click()`);
  await until(() => evaluate(`location.pathname === '/login' && Boolean(document.querySelector('input[type="email"]'))`), 'browser logout');
  assert.equal(await AuthSession.countDocuments({ userId }), 0);
  await call('Page.navigate', { url: `${web}/dashboard` });
  await until(() => evaluate(`location.pathname === '/login' && Boolean(document.querySelector('input[type="email"]'))`), 'protected-route redirect');
  await fill('input[type="email"]', email); await fill('input[type="password"]', password); await evaluate(`document.querySelector('form button').click()`);
  await until(() => evaluate(`location.pathname === '/dashboard' && document.body.innerText.includes('Your dashboard')`), 'browser login');
  evidence.checks.logoutProtectedRouteLogin = true;
  evidence.runtimeErrors = browser.errors; assert.deepEqual(browser.errors, []);
  console.log(JSON.stringify(evidence));
} catch (error) { evidence.failure = error.stack || error.message; evidence.runtimeErrors = browser?.errors || []; console.error(error.stack || error.message); process.exitCode = 1; }
finally {
  await browser?.close();
  userId ||= (await User.findOne({ email }).lean())?._id;
  if (userId) { for (const Model of [PriceObservation, Notification, DisruptionPrediction, FareIntelligenceAnalysis, IntelligenceReport, TrackedFlight, AuthSession]) await Model.deleteMany({ userId }); await User.deleteOne({ _id: userId }); }
  await mongoose.disconnect();
  await mkdir('../docs/qa/production-2026-10-28', { recursive: true });
  await writeFile('../docs/qa/production-2026-10-28/browser-user-journeys.json', JSON.stringify(evidence, null, 2));
}
